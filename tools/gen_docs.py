#!/usr/bin/env python3
"""Generate the indexes and navigation that follow from the documentation metadata.

  docs/modules/README.md     module catalog by track
  docs/learning-path.md      levels and the prerequisite graph
  docs/system/README.md      architecture diagrams, component pages, connections, walks
  navigation block           at the end of every written page (between the nav markers)

Run without arguments to write the files; with --check to fail if any would change.
"""
import os
import re
import sys

import content as C

HEADER = '<!-- Generated by tools/gen_docs.py from the page front matter and docs/system/architecture.yaml. Do not edit. -->\n\n'
NAV_BEGIN = '<!-- nav:begin (generated by tools/gen_docs.py from the front matter; do not edit) -->'
NAV_END = '<!-- nav:end -->'
ARCH_BEGIN = '<!-- arch:begin (generated by tools/gen_docs.py from docs/system/architecture.yaml; do not edit) -->'
ARCH_END = '<!-- arch:end -->'
STATUS_LABEL = {
    'validated': 'validated', 'validated-old': 'validated on an earlier fabric', 'simulated': 'simulated',
    'experimental': 'experimental', 'planned': 'planned', 'held': 'held until tested on the board',
}
REPRO_SHORT = {'sim': 'simulation', 'base': 'shared baseline', 'dedicated-fabric': 'own fabric build',
               'full-system': 'full system', 'tool': 'Libero on a PC', 'doc': 'read', 'none': 'read'}


def link(meta, frm):
    """Markdown link to a module from a file in directory frm, or plain text if it is only planned."""
    label = '%s %s' % (meta['id'], meta['title'])
    if 'file' not in meta:
        return label + ' *(planned)*'
    return '[%s](%s)' % (label, os.path.relpath(meta['file'], frm))


def gen_catalog(mods):
    out = [HEADER, '# Module catalog\n\n',
           'Every module is one page with the same structure: what it teaches, what you need, how it works, '
           'how to run it, what you should see, and the evidence behind every number. '
           'Modules marked *planned* are scoped but not yet written.\n\n',
           '**How to run** tells you what a module needs: *simulation* needs only Icarus Verilog and Python; '
           '*shared baseline* needs the board with the pfdaq fabric and image, which one build serves for all such modules; '
           '*read* is explanation backed by recorded evidence.\n\n']
    for key, letter, title in C.TRACKS:
        rows = sorted([m for m in mods.values() if m.get('track') == key], key=C.module_sort_key)
        if not rows:
            continue
        out.append('## %s\n\n| Module | Level | How to run | Status |\n|---|---|---|---|\n' % title)
        for m in rows:
            out.append('| %s<br>%s | %s | %s | %s |\n' % (
                link(m, 'docs/modules'), m['summary'], m['level'], REPRO_SHORT[m['repro']], STATUS_LABEL[m['status']]))
        out.append('\n')
    n_written = sum(1 for m in mods.values() if 'file' in m)
    out.append('%d modules, %d written.\n' % (len(mods), n_written))
    return ''.join(out)


def gen_learning_path(mods):
    out = [HEADER, '# Learning path\n\n',
           'Modules are grouped in five levels. Nothing forces an order: every module lists what it needs, '
           'and the graph below shows those prerequisites. If you already know a topic, skip it.\n\n']
    names = {1: 'Level 1: fundamentals', 2: 'Level 2: isolated building blocks', 3: 'Level 3: subsystem integration',
             4: 'Level 4: the complete application and its hard parts', 5: 'Level 5: advanced engineering'}
    for lvl in range(1, 6):
        rows = sorted([m for m in mods.values() if m.get('level') == lvl], key=C.module_sort_key)
        if not rows:
            continue
        out.append('## %s\n\n' % names[lvl])
        for m in rows:
            needs = ', '.join(m.get('needs') or []) or 'nothing'
            out.append('- %s. Needs: %s.\n' % (link(m, 'docs'), needs))
        out.append('\n')
    out.append('## Prerequisite graph\n\nAn arrow means "read this first". Case studies are left out; each names its own background.\n\n```mermaid\nflowchart LR\n')
    shown = [m for m in mods.values() if m.get('track') not in ('case-study',)]
    for key, letter, title in C.TRACKS:
        rows = sorted([m for m in shown if m.get('track') == key], key=C.module_sort_key)
        if not rows:
            continue
        out.append('  subgraph %s["%s"]\n' % (letter, title))
        for m in rows:
            out.append('    %s["%s %s"]\n' % (m['id'], m['id'], m['title'].replace('"', "'")))
        out.append('  end\n')
    ids = {m['id'] for m in shown}
    for m in sorted(shown, key=C.module_sort_key):
        for n in m.get('needs') or []:
            if n in ids:
                out.append('  %s --> %s\n' % (n, m['id']))
    out.append('```\n')
    return ''.join(out)


def mid(node_id):
    return node_id.replace('-', '_')


def mermaid(arch, node_ids, edge_kinds, direction='LR'):
    nodes = {n['id']: n for n in arch['nodes']}
    keep = set(node_ids)
    # include ancestors as subgraphs
    children = {}
    for nid in list(keep):
        p = nodes[nid].get('parent')
        while p:
            keep.add(p)
            p = nodes[p].get('parent')
    for nid in keep:
        children.setdefault(nodes[nid].get('parent'), []).append(nid)
    order = [n['id'] for n in arch['nodes']]
    lines = ['```mermaid', 'flowchart %s' % direction]

    def emit(nid, depth):
        pad = '  ' * depth
        kids = sorted(children.get(nid, []), key=order.index)
        if kids:
            lines.append('%ssubgraph %s["%s"]' % (pad, mid(nid), nodes[nid]['title']))
            for k in kids:
                emit(k, depth + 1)
            lines.append('%send' % pad)
        else:
            lines.append('%s%s["%s"]' % (pad, mid(nid), nodes[nid]['title']))

    for top in sorted(children.get(None, []), key=order.index):
        emit(top, 1)
    arrow = {'irq': '-.->', 'boot': '==>', 'axi4-stream': '==>'}
    for e in arch['edges']:
        if e['kind'] in edge_kinds and e['from'] in keep and e['to'] in keep:
            lines.append('  %s %s|"%s"| %s' % (mid(e['from']), arrow.get(e['kind'], '-->'), e['label'].replace('"', "'"), mid(e['to'])))
    lines.append('```')
    return '\n'.join(lines) + '\n'


def gen_system(arch, mods):
    nodes = {n['id']: n for n in arch['nodes']}
    edges = arch['edges']
    learn = {}
    for m in sorted(mods.values(), key=C.module_sort_key):
        for k in ('hardware', 'software'):
            for nid in m.get(k) or []:
                learn.setdefault(nid, []).append(m)
    b = arch['baseline']
    out = [HEADER, '# The system, component by component\n\n',
           'Baseline: %s on the %s (%s), fabric v%s, design version %s.\n\n' % (
               b['tag'], b['board'], b['device'], b['fabric'], b['design_version']),
           'This page is generated from [`architecture.yaml`](architecture.yaml), the same data that drives the '
           'architecture explorer on the website. Each component lists what it connects to and which modules explain it.\n\n',
           '## Data and interrupt paths\n\nSolid arrows are bus connections, thick arrows the data stream, dotted arrows interrupts.\n\n']
    hw = [n['id'] for n in arch['nodes'] if n['kind'] in ('hart', 'mss-block', 'bus', 'fabric-block', 'memory')
          and n['id'] not in ('mss-gpio2', 'mss-uarts', 'refdesign-peripherals', 'fabric-clocks', 'pfdaq-fir-src',
                              'ddr-u54-4-image', 'e51')]
    out.append(mermaid(arch, hw, ('apb', 'ahb', 'axi4', 'axi4-stream', 'irq', 'mem')))
    out.append('\n## Software and who runs where\n\n')
    sw = [n['id'] for n in arch['nodes'] if n['kind'] in ('software', 'hart')] + ['ddr-rpmsg', 'ihc']
    out.append(mermaid(arch, sw, ('runs', 'rpmsg', 'uses', 'boot'), 'TB'))
    out.append('\n## Walks through the system\n\n')
    for p in arch.get('paths', []):
        out.append('### %s\n\n' % p['title'])
        for i, s in enumerate(p['steps'], 1):
            e = next(x for x in edges if x['id'] == s['edge'])
            out.append('%d. %s *(%s → %s)*\n' % (i, s['say'], nodes[e['from']]['title'], nodes[e['to']]['title']))
        out.append('\n')
    out.append('## Components\n\n')
    for n in arch['nodes']:
        out.append('### %s\n\n<a id="%s"></a>\n\n%s\n\n' % (n['title'], n['id'], n['summary']))
        if n.get('parent'):
            out.append('- **Part of:** [%s](#%s)\n' % (nodes[n['parent']]['title'], n['parent']))
        kids = [c for c in arch['nodes'] if c.get('parent') == n['id']]
        if kids:
            out.append('- **Contains:** %s\n' % ', '.join('[%s](#%s)' % (c['title'], c['id']) for c in kids))
        for k, v in (n.get('facts') or {}).items():
            out.append('- **%s:** %s\n' % (k.replace('_', ' ').capitalize(), v))
        for e in edges:
            if e['from'] == n['id']:
                out.append('- → [%s](#%s): %s%s\n' % (nodes[e['to']]['title'], e['to'], e['label'], '. ' + e['detail'] if e.get('detail') else ''))
        for e in edges:
            if e['to'] == n['id']:
                out.append('- ← [%s](#%s): %s%s\n' % (nodes[e['from']]['title'], e['from'], e['label'], '. ' + e['detail'] if e.get('detail') else ''))
        for s in C.norm_sources(n.get('sources')):
            syms = ' (%s)' % ', '.join('`%s`' % x for x in s['symbols']) if s.get('symbols') else ''
            out.append('- **Source:** [`%s`](%s)%s\n' % (s['path'], os.path.relpath(s['path'], 'docs/system'), syms))
        if n['id'] in learn:
            out.append('- **Learn how this works:** %s\n' % '; '.join(link(m, 'docs/system') for m in learn[n['id']]))
        out.append('\n')
    return ''.join(out)


def gen_nav(page, mods, arch, evidence):
    nodes = {n['id']: n for n in arch['nodes']}
    frm = os.path.dirname(page['file'])
    rows = []
    if page.get('needs'):
        rows.append(('Read first', '<br>'.join(link(mods[i], frm) for i in page['needs'])))
    rows.append(('How to run', C.REPRO[page['repro']]))
    ids = (page.get('hardware') or []) + (page.get('software') or [])
    if ids:
        rows.append(('In the system', ' · '.join('[%s](%s#%s)' % (
            nodes[i]['title'], os.path.relpath('docs/system/README.md', frm), i) for i in ids)))
    src = C.norm_sources(page.get('sources'))
    if src:
        rows.append(('Source', '<br>'.join('[`%s`](%s)%s' % (
            s['path'], os.path.relpath(s['path'], frm),
            ': ' + ', '.join('`%s`' % x for x in s['symbols']) if s.get('symbols') else '') for s in src)))
    if page.get('evidence'):
        rows.append(('Evidence', '<br>'.join('[%s](%s) (%s%s, %s)' % (
            evidence[i]['title'], os.path.relpath(evidence[i]['path'], frm), evidence[i]['class'],
            C.fabric_label(evidence[i]), evidence[i]['date']) for i in page['evidence'])))
    if page.get('related'):
        rows.append(('Related', '<br>'.join(link(mods[i], frm) for i in page['related'])))
    rows.append(('Status', STATUS_LABEL[page['status']]))
    t = ['---', '', '| | |', '|---|---|'] + ['| **%s** | %s |' % r for r in rows]
    return NAV_BEGIN + '\n' + '\n'.join(t) + '\n' + NAV_END + '\n'


def with_nav(text, nav):
    if NAV_BEGIN in text:
        return re.sub(re.escape(NAV_BEGIN) + r'.*?' + re.escape(NAV_END) + r'\n?', lambda m: nav, text, flags=re.S)
    return text.rstrip('\n') + '\n\n' + nav


def main():
    check = '--check' in sys.argv
    arch = C.load_architecture()
    mods = C.all_modules()
    evidence = C.load_evidence()
    targets = {
        'docs/modules/README.md': gen_catalog(mods),
        'docs/learning-path.md': gen_learning_path(mods),
        'docs/system/README.md': gen_system(arch, mods),
    }
    hw = [n['id'] for n in arch['nodes'] if n['id'] in (
        'u54-linux', 'u54-4', 'plic', 'fic0', 'fic3', 'pfdaq-stream-src', 'pfdaq-latency', 'dma', 'ihc', 'ddr-noncached')]
    readme = open(os.path.join(C.ROOT, 'README.md')).read()
    block = ARCH_BEGIN + '\n' + mermaid(arch, hw, ('apb', 'axi4', 'axi4-stream', 'irq', 'mem')) + ARCH_END
    targets['README.md'] = re.sub(re.escape(ARCH_BEGIN) + r'.*?' + re.escape(ARCH_END), lambda m: block, readme, flags=re.S)
    for p in C.load_pages():
        if 'id' not in p:
            continue
        with open(os.path.join(C.ROOT, p['file'])) as f:
            text = f.read()
        try:
            targets[p['file']] = with_nav(text, gen_nav(p, mods, arch, evidence))
        except KeyError as e:
            print('%s: unresolved reference %s' % (p['file'], e))
            return 1
    stale = []
    for path, text in targets.items():
        full = os.path.join(C.ROOT, path)
        old = open(full).read() if os.path.isfile(full) else None
        if old != text:
            stale.append(path)
            if not check:
                os.makedirs(os.path.dirname(full), exist_ok=True)
                with open(full, 'w') as f:
                    f.write(text)
    if check and stale:
        print('out of date: ' + ', '.join(stale))
        return 1
    if not check:
        print('%d files generated, %d changed' % (len(targets), len(stale)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
